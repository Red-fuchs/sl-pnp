#!/usr/bin/env python3
"""Generate Sources/SLCore/PromptsGen.swift from the single source of truth gm-loop/prompt.py (usage: tools/gen_prompts.py [path/to/prompt.py])."""
import json, sys, pathlib
src_path = sys.argv[1] if len(sys.argv) > 1 else str(pathlib.Path.home() / "Claude-Workspace/gm-bench/gm-loop/prompt.py")
src = open(src_path).read()
ns = {}
exec(src, ns)
FEW = [(m["role"], m["content"]) for m in ns["FEW"]]
raw = lambda s: '#"""\n' + s + '\n"""#'
fig = ns["figur_block"]("@@")
out = f'''// GENERATED by tools/gen_prompts.py from gm-loop/prompt.py ({ns["VERSION"]}) - do not edit by hand.
import Foundation

public let PROMPT_VERSION = "{ns["VERSION"]}"

let SYS_TEXT = {raw(ns["SYS"])}

let TOOLS_TEXT = {raw(ns["TOOLS"])}

public let SYS = SYS_TEXT + "\\n\\n" + TOOLS_TEXT

public func figurBlock(_ f: String?) -> String {{ f.map {{ {json.dumps(fig, ensure_ascii=False).replace("@@", "\\($0)")} }} ?? "" }}

let DIRS: [String: String] = {json.dumps(ns["DIRS"], ensure_ascii=False).replace("{", "[").replace("}", "]")}

public let DELTA_SYS = {raw(ns["DELTA_SYS"])}

public let DELTA_SCHEMA = {raw(json.dumps(ns["DELTA_SCHEMA"], ensure_ascii=False, separators=(",", ":")))}

public let FEW: [Msg] = [
''' + "\n".join(f'  .{"u" if r == "user" else "m"}({json.dumps(t, ensure_ascii=False)}),' for r, t in FEW) + "\n]\n"
open(pathlib.Path(__file__).resolve().parent.parent / "Sources/SLCore/PromptsGen.swift", "w").write(out)
print("ok", ns["VERSION"], len(FEW), "few-shot messages")
