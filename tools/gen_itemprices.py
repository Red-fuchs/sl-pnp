#!/usr/bin/env python3
"""handout/data/items.json -> Sources/SLCore/ItemPrices.swift (creation shop: name alternatives and Taler price, rounded to 5 T, min 3 T)."""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(os.path.join(root, "handout/data/items.json")))
rows = []
for k in d["kategorien"]:
    for it in k["items"]:
        t = it["preis_h"] / 4
        t = max(3, round(t / 5) * 5) if t >= 10 else max(1, round(t))
        alts = [a.strip().lower() for a in it["name"].replace("(", "/").replace(")", "").split("/") if len(a.strip()) >= 4 and a.strip().lower() != "satz"]
        rows.append((it["name"], alts, int(t)))
out = ["// generated by tools/gen_itemprices.py from handout/data/items.json - do not edit", "enum ItemPrices {", "  static let list: [(name: String, alts: [String], taler: Int)] = ["]
for n, a, t in rows:
    out.append('    (%s, [%s], %d),' % (json.dumps(n, ensure_ascii=False), ", ".join(json.dumps(x, ensure_ascii=False) for x in a), t))
out += ["  ]", "}"]
open(os.path.join(root, "Sources/SLCore/ItemPrices.swift"), "w").write("\n".join(out) + "\n")
print(len(rows), "items")
